func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "verify generated contracts without writing")
	flag.Parse()

	descriptors, err := api.ProjectControlDescriptors()
	fatalIf(err)
	catalog, err := projectcontrol.BuildToolCatalog(descriptors)
	fatalIf(err)
	contracts, err := api.ProjectControlActionContracts()
	fatalIf(err)

	absRoot, err := filepath.Abs(*root)
	fatalIf(err)
	exclusions, err := loadOperationExclusions(filepath.Join(
		absRoot, "packages", "project-control", "operation-exclusions.v1.json",
	))
	fatalIf(err)
	matrix, err := projectcontrol.BuildActionMatrix(contracts, exclusions...)
	fatalIf(err)
	outputs := map[string]any{
		"packages/mcp/tool-catalog.v1.json":              catalog,
		"packages/mcp/protocol-fixtures.v1.json":         protocolFixtureDocument(),
		"packages/project-control/action-matrix.v1.json": matrix,
	}
	for relativePath, value := range outputs {
		encoded, marshalErr := json.MarshalIndent(value, "", "  ")
		fatalIf(marshalErr)
		encoded = append(encoded, '\n')
		fatalIf(writeOrCheckGenerated(absRoot, relativePath, encoded, *check))
	}
	hashSource, err := format.Source([]byte(fmt.Sprintf(`// Code generated by cmd/project-control-contracts; DO NOT EDIT.

package projectcontrol

const (
	GeneratedToolCatalogHash = %q
	GeneratedActionMatrixHash = %q
)
`, catalog.CatalogHash, matrix.MatrixHash)))
	fatalIf(err)
	fatalIf(writeOrCheckGenerated(
		absRoot,
		"internal/projectcontrol/generated_contract_hashes.go",
		hashSource,
		*check,
	))
}

