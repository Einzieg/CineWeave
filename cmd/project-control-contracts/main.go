func writeOrCheckGenerated(root, relativePath string, content []byte, check bool) error {
	path := filepath.Join(root, filepath.FromSlash(relativePath))
	if check {
		existing, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read generated %s: %w", relativePath, err)
		}
		if !bytes.Equal(existing, content) {
			return fmt.Errorf("%s is stale; run go run ./cmd/project-control-contracts", relativePath)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0o644)
}

func loadOperationExclusions(path string) ([]projectcontrol.OperationExclusion, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var document struct {
		SchemaVersion string                              `json:"schemaVersion"`
		Exclusions    []projectcontrol.OperationExclusion `json:"exclusions"`
	}
	if err := json.Unmarshal(raw, &document); err != nil {
		return nil, fmt.Errorf("decode project control operation exclusions: %w", err)
	}
	if document.SchemaVersion != "cineweave.project-control-operation-exclusions.v1" {
		return nil, fmt.Errorf("project control operation exclusions schemaVersion is invalid")
	}
	return document.Exclusions, nil
}

func fatalIf(err error) {
	if err == nil {
		return
	}
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
